#!/usr/bin/env python3
"""r6: candidate8 vs candidate7 vs the authors' code.  Reads the run directories of run_r6.sh and run_tight.sh
and prints a Markdown report.
   analyze_r6.py <W of run_r6.sh> [<OUT of run_tight.sh>] > RESULTS.md
Pure stdlib.  A pair counts as "same work" when both arms made the same number of black-box calls and spent
no time in the base case (n6 timers 0): the arms then ran the same code and only timing noise separates them."""
import csv, glob, math, os, random, statistics as st, sys

W = sys.argv[1]
TIGHT = sys.argv[2] if len(sys.argv) > 2 else None
ARMS = ('gitlab', 'candidate7', 'candidate8')
NAME = {'gitlab': "authors' code", 'candidate7': 'candidate7', 'candidate8': 'candidate8'}

def load_lmf(d):
    rows = {}
    for arm in ARMS:
        for p in sorted(glob.glob(f'{d}/{arm}/*.csv')):
            unit = os.path.basename(p)[:-4]
            with open(p) as f:
                for i, r in enumerate(csv.DictReader(f)):
                    rows.setdefault((unit, i), {})[arm] = r
    return [v for k, v in sorted(rows.items()) if all(a in v for a in ARMS)]

def gm(xs): return math.exp(sum(map(math.log, xs)) / len(xs))

def boot_ci(xs, n=2000, seed=1):
    rnd = random.Random(seed); logs = [math.log(x) for x in xs]; k = len(logs); out = []
    for _ in range(n):
        s = rnd.choices(logs, k=k); out.append(math.exp(sum(s) / k))
    out.sort(); return out[int(0.025 * n)], out[int(0.975 * n) - 1]

def f(r, k): return float(r[k])

def same_work(a, b):
    return a['bbcalls'] == b['bbcalls'] and f(a, 'n6_arr_ms') == 0 == f(b, 'n6_arr_ms') and f(a, 'n6_fre_ms') == 0 == f(b, 'n6_fre_ms')

print('# r6 — candidate8 vs candidate7 vs the authors\' code\n')
print('Generated by `scripts/analyze_r6.py` from the run directories. Ratios are slower ÷ faster arm as named; '
      '"faster" means strictly less time on that instance.\n')

for title, sub in (('Characters LMF (21,000 pairs)', 'chars'), ('Sigspatial LMF (1,000 pairs)', 'sig')):
    rows = load_lmf(f'{W}/{sub}')
    if not rows: continue
    print(f'## {title}\n')
    print(f'Pairs measured by all three arms: {len(rows)}.\n')
    print('| arm | time (ms) | ms/inst. | black-box calls | calls/inst. |')
    print('|---|--:|--:|--:|--:|')
    for a in ARMS:
        t = sum(f(r[a], 'time_ms') for r in rows); c = sum(f(r[a], 'bbcalls') for r in rows)
        print(f'| {NAME[a]} | {t:,.0f} | {t/len(rows):.2f} | {c:,.0f} | {c/len(rows):,.1f} |')
    print()
    print('| comparison | total time ratio | per-instance geomean [95 % CI] | median | numerator arm faster | calls ratio |')
    print('|---|--:|--:|--:|--:|--:|')
    for num, den in (('gitlab', 'candidate7'), ('gitlab', 'candidate8'), ('candidate7', 'candidate8')):
        rs = [f(r[num], 'time_ms') / f(r[den], 'time_ms') for r in rows]
        lo, hi = boot_ci(rs)
        tt = sum(f(r[num], 'time_ms') for r in rows) / sum(f(r[den], 'time_ms') for r in rows)
        cc = sum(f(r[num], 'bbcalls') for r in rows) / sum(f(r[den], 'bbcalls') for r in rows)
        slower = sum(1 for x in rs if x < 1)
        print(f'| {NAME[num]} ÷ {NAME[den]} | {tt:.2f}× | {gm(rs):.3f}× [{lo:.3f}, {hi:.3f}] | {st.median(rs):.3f}× | '
              f'{NAME[den]} slower on {slower} ({100*slower/len(rows):.2f} %) | {cc:.2f}× |')
    print()
    print('Instances where the proposed arm is slower than the authors\' code, split by whether both arms did the same work:\n')
    print('| arm | slower | same work (timing noise) | different work | of which the arm made more black-box calls |')
    print('|---|--:|--:|--:|--:|')
    for a in ('candidate7', 'candidate8'):
        s = [r for r in rows if f(r[a], 'time_ms') > f(r['gitlab'], 'time_ms')]
        sw = [r for r in s if same_work(r[a], r['gitlab'])]
        dw = [r for r in s if not same_work(r[a], r['gitlab'])]
        more = [r for r in dw if f(r[a], 'bbcalls') > f(r['gitlab'], 'bbcalls')]
        print(f'| {NAME[a]} | {len(s)} ({100*len(s)/len(rows):.2f} %) | {len(sw)} | {len(dw)} | {len(more)} |')
    sw_all = [r for r in rows if same_work(r['candidate8'], r['gitlab'])]
    if sw_all:
        rs = [f(r['gitlab'], 'time_ms') / f(r['candidate8'], 'time_ms') for r in sw_all]
        print(f'\nSame-work instances (authors\' code vs candidate8): {len(sw_all)}, geomean {gm(rs):.3f}×, '
              f'candidate8 slower on {sum(1 for x in rs if x < 1)} ({100*sum(1 for x in rs if x < 1)/len(rs):.1f} %).')
    more7 = sum(1 for r in rows if f(r['candidate7'], 'bbcalls') > f(r['gitlab'], 'bbcalls'))
    more8 = sum(1 for r in rows if f(r['candidate8'], 'bbcalls') > f(r['gitlab'], 'bbcalls'))
    print(f'\nInstances with more black-box calls than the authors\' code (deterministic): candidate7 {more7}, candidate8 {more8}.')
    print('\nValues: largest |difference| between arms, and instances over 1e-7:\n')
    for x, y in (('gitlab', 'candidate7'), ('gitlab', 'candidate8'), ('candidate7', 'candidate8')):
        d = [abs(f(r[x], 'value') - f(r[y], 'value')) for r in rows]
        print(f'- {NAME[x]} vs {NAME[y]}: max {max(d):.3g}, over 1e-7: {sum(1 for v in d if v > 1e-7)}')
    dv = [f(r['candidate8'], 'value') - f(r['candidate7'], 'value') for r in rows]
    print(f'- candidate8 − candidate7: min {min(dv):.3g}, max {max(dv):.3g}, candidate8 lower on {sum(1 for v in dv if v < 0)}, '
          f'higher on {sum(1 for v in dv if v > 0)}')
    print()

dec = f'{W}/dec4'
if os.path.isdir(dec):
    print('## Decider, factors 1 ± 4^l (candidate7 vs candidate8)\n')
    print('| benchmark | queries | wrong c7 | wrong c8 | time c7 (ms) | time c8 (ms) | c7 ÷ c8 | calls c7 | calls c8 |')
    print('|---|--:|--:|--:|--:|--:|--:|--:|--:|')
    for b in ('characters_uci_same', 'characters_uci_all', 'sigspatial'):
        tot = {a: [0, 0, 0, 0] for a in ('candidate7', 'candidate8')}   # n, wrong, time, calls
        for a in tot:
            for p in glob.glob(f'{dec}/{a}/{b}_paperq4_*.csv'):
                e = 1 if p.endswith('_plus.csv') else 0
                for r in csv.DictReader(open(p)):
                    tot[a][0] += 1; tot[a][1] += int(r['answer']) != e; tot[a][2] += f(r, 'time_ms'); tot[a][3] += f(r, 'bbcalls')
        c7, c8 = tot['candidate7'], tot['candidate8']
        if c7[0]:
            print(f'| {b} | {c7[0]:,} | {c7[1]} | {c8[1]} | {c7[2]:,.0f} | {c8[2]:,.0f} | {c7[2]/c8[2]:.2f}× | {c7[3]:,.0f} | {c8[3]:,.0f} |')
    print()

if TIGHT:
    print('## Real data at v ± 5e-8 (v = the kit\'s near-threshold value; truth: plus YES, minus NO)\n')
    print('| arm | file | queries | wrong |')
    print('|---|---|--:|--:|')
    for a in sorted(os.listdir(TIGHT)):
        for p in sorted(glob.glob(f'{TIGHT}/{a}/*.csv')):
            e = 0 if '_m5e-8_' in p else 1
            rs = list(csv.DictReader(open(p)))
            print(f'| {a} | {os.path.basename(p)[:-4]} | {len(rs):,} | {sum(1 for r in rs if int(r["answer"]) != e)} |')
    print()
